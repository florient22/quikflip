"""Download the web fonts QuikFlip uses (latin subset, woff2) so the app never calls Google at runtime.

Usage:  python3 tools/fetch_fonts.py
Skips files that already exist, so running it again does nothing. Writes web/fonts/*.woff2 and web/fonts/fonts.css.
All fonts are licensed under the SIL Open Font License 1.1.
"""
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "web" / "fonts"
# A modern browser user agent makes Google Fonts serve woff2.
USER_AGENT = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
FAMILIES = {
    "figtree": "Figtree:wght@400..800",
    "bricolage-grotesque": "Bricolage+Grotesque:opsz,wght@12..96,400..800",
    "archivo-black": "Archivo+Black",
    "ibm-plex-mono": "IBM+Plex+Mono:wght@500;700",
    "anton": "Anton",
    "bungee": "Bungee",
    "manrope": "Manrope:wght@500..800",
    "unbounded": "Unbounded:wght@600..900",
    "dm-sans": "DM+Sans:opsz,wght@9..40,500..700",
    "titan-one": "Titan+One",
    "permanent-marker": "Permanent+Marker",
    "rubik": "Rubik:wght@500..800",
}
LATIN_BLOCK = re.compile(r"/\* latin \*/\s*@font-face\s*{(.*?)}", re.S)


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def main() -> int:
    FONTS.mkdir(parents=True, exist_ok=True)
    faces = []
    downloaded = 0
    try:
        for slug, query in FAMILIES.items():
            css = fetch(f"https://fonts.googleapis.com/css2?family={query}&display=swap").decode("utf-8")
            for index, block in enumerate(LATIN_BLOCK.findall(css)):
                family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
                weight = re.search(r"font-weight:\s*([^;]+);", block).group(1).strip()
                url = re.search(r"src:\s*url\(([^)]+)\)", block).group(1)
                filename = f"{slug}-{index}.woff2"
                target = FONTS / filename
                if not target.exists():
                    target.write_bytes(fetch(url))
                    downloaded += 1
                faces.append(
                    f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-weight: {weight};\n"
                    f"  font-display: swap;\n  src: url('{filename}') format('woff2');\n}}\n"
                )
    except OSError as error:
        print(f"error: could not download fonts: {error}", file=sys.stderr)
        return 1
    header = "/* Generated by tools/fetch_fonts.py. Fonts: SIL Open Font License 1.1. */\n"
    (FONTS / "fonts.css").write_text(header + "\n".join(faces), encoding="utf-8")
    print(f"Fonts: {len(faces)} faces in web/fonts/fonts.css, {downloaded} new files downloaded")
    return 0


if __name__ == "__main__":
    sys.exit(main())
